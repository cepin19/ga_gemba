def main():
    scores = {}
    for line in open(sys.argv[1], encoding="utf-8"):
        name, *values = line.rstrip("\n").split("\t")
        scores[name] = [float(v) for v in values]
    print(f"{'run':<18}{'':<6}" + "".join(f"{c:>9}" for c in COLS))
    missing = []
    for target, rows in PAPER.items():
        for w, paper in zip(WEIGHTS, rows):
            name = f"{target}_w{w}"
            if name not in scores:
                missing.append(name)
                continue
            new = scores[name]
            print(f"{name:<18}{'new':<6}" + "".join(f"{v:>9.3f}" for v in new))
            print(f"{'':<18}{'paper':<6}" + "".join(f"{v:>9.3f}" for v in paper))
            print(f"{'':<18}{'diff':<6}" + "".join(f"{a - b:>+9.3f}" for a, b in zip(new, paper)))
    if missing:
        print(f"\nNOT SCORED ({len(missing)}): {' '.join(missing)}")


if __name__ == "__main__":
    main()
